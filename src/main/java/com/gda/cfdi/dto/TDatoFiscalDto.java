package com.gda.cfdi.dto;

public class TDatoFiscalDto {

	private Integer kdatofiscal;
	private String srazonsocial;
	private String srfc;
	private String sdireccion;
	private Integer ccodigopostal;
	private String spais;
	
	public Integer getKdatofiscal() {
		return kdatofiscal;
	}
	public void setKdatofiscal(Integer kdatofiscal) {
		this.kdatofiscal = kdatofiscal;
	}
	public String getSrazonsocial() {
		return srazonsocial;
	}
	public void setSrazonsocial(String srazonsocial) {
		this.srazonsocial = srazonsocial;
	}
	public String getSrfc() {
		return srfc;
	}
	public void setSrfc(String srfc) {
		this.srfc = srfc;
	}
	public String getSdireccion() {
		return sdireccion;
	}
	public void setSdireccion(String sdireccion) {
		this.sdireccion = sdireccion;
	}
	public Integer getCcodigopostal() {
		return ccodigopostal;
	}
	public void setCcodigopostal(Integer ccodigopostal) {
		this.ccodigopostal = ccodigopostal;
	}
	public String getSpais() {
		return spais;
	}
	public void setSpais(String spais) {
		this.spais = spais;
	}
	
	
	
}
